export interface SocialData {
  github: string;
  email: string;
  weibo: string;
  bilibili: string;
}

export function loadSocial(): SocialData {
  try {
    const raw = localStorage.getItem(KEY);
    return raw ? JSON.parse(raw) : { github: "", email: "", weibo: "", bilibili: "" };
  } catch {
    return { github: "", email: "", weibo: "", bilibili: "" };
  }
}

export function saveSocial(data: SocialData): void {
  localStorage.setItem(KEY, JSON.stringify(data));
}

